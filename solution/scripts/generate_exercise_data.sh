# Generates meteorological station exercise files for Lesson 01.
# Run from the course root: bash scripts/generate_exercise_data.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COURSE_DIR="$(dirname "$SCRIPT_DIR")"
INCOMING="$COURSE_DIR/exercises/meteorological/incoming"
NODATA_DIR="$COURSE_DIR/exercises/nodata-replace"

HEADER="station_id date temp_c humidity_pct wind_ms precip_mm pressure_hPa solar_wm2 dewpoint_c visibility_km cloud_cover_pct"
STATION="FF-MET-042"

# --- Exercise 2: ~1460 files (2 years, raw + post-processed) ---
mkdir -p "$INCOMING"

generate_row() {
  local date="$1"
  local kind="$2"
  if [[ "$kind" == "raw-data" ]]; then
    # Slightly noisier values for raw files
    echo "$STATION $date 12.4 68.2 3.1 0.0 1013.2 420.5 6.8 12.0 45"
  else
    echo "$STATION $date 12.1 67.5 3.0 0.0 1013.0 418.0 6.5 12.5 42"
  fi
}

count=0
for year in 2023 2024; do
  for month in $(seq -w 1 12); do
    # Approximate 30 days per month for exercise volume
    for day in $(seq -w 1 30); do
      date="${year}-${month}-${day}"
      for kind in raw-data post-processed; do
        file="$INCOMING/${date}_${kind}.txt"
        {
          echo "$HEADER"
          generate_row "$date" "$kind"
        } > "$file"
        count=$((count + 1))
      done
    done
  done
done

echo "Created $count meteorological files in $INCOMING"

